def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("usage: python3 report.py <results-dir>")
    results_dir = Path(sys.argv[1]).resolve()
    data = load(results_dir)
    write_csv(data, results_dir / "summary.csv")
